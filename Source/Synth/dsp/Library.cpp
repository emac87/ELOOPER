    // Operator builder: ratio (coarse.fine), output level, EG rates / levels (L4 is always 0).
    struct O {
        Dx7Op o;
        O (int coarse, int fine, int level, std::array<int, 4> r, std::array<int, 3> l)
        {
            o.freqCoarse = (uint8_t) coarse; o.freqFine = (uint8_t) fine; o.outputLevel = (uint8_t) level;
            for (int i = 0; i < 4; ++i) o.egRate[i] = (uint8_t) r[(size_t) i];
            for (int i = 0; i < 3; ++i) o.egLevel[i] = (uint8_t) l[(size_t) i];
            o.egLevel[3] = 0;
            o.keyVelSens = 2;
        }
        O& vel (int v) { o.keyVelSens = (uint8_t) v; return *this; }
        O& det (int d) { o.detune = (uint8_t) d; return *this; }
        O& rs (int v) { o.kbdRateScaling = (uint8_t) v; return *this; }
        O& am (int v) { o.ampModSens = (uint8_t) v; return *this; }
        O& fixed (int coarse, int fine) { o.oscMode = 1; o.freqCoarse = (uint8_t) coarse; o.freqFine = (uint8_t) fine; return *this; }
        // level scaling around a break point: depth left / right, curves 0..3 (-LIN,-EXP,+EXP,+LIN)
        O& ks (int bp, int ld, int rd, int lc, int rc)
        {
            o.kbdBreakPoint = (uint8_t) bp; o.kbdLeftDepth = (uint8_t) ld; o.kbdRightDepth = (uint8_t) rd;
            o.kbdLeftCurve = (uint8_t) lc; o.kbdRightCurve = (uint8_t) rc;
            return *this;
        }
        operator Dx7Op() const { return o; }
    };
    Dx7Op off() { Dx7Op o; o.outputLevel = 0; o.egLevel[3] = 0; return o; }

    void setName (Dx7Patch& v, const char* name)
    {
        std::fill (std::begin (v.name), std::end (v.name), 0);
        for (int i = 0; i < 10 && name[i]; ++i) v.name[i] = name[i];
    }

    Dx7Patch voice (const char* name, int algorithm, int feedback, std::array<Dx7Op, 6> ops)
    {
        Dx7Patch v = dx7InitVoice();
        v.algorithm = (uint8_t) (algorithm - 1);
        v.feedback = (uint8_t) feedback;
        v.op = ops;
        setName (v, name);
        return v;
    }

    void pitchEg (Dx7Patch& v, std::array<int, 4> r, std::array<int, 4> l)
    {
        for (int i = 0; i < 4; ++i) { v.pitchEgRate[i] = (uint8_t) r[(size_t) i]; v.pitchEgLevel[i] = (uint8_t) l[(size_t) i]; }
    }

    void lfo (Dx7Patch& v, int speed, int delay, int pmd, int amd, int wave, int pitchSens)
    {
        v.lfoSpeed = (uint8_t) speed; v.lfoDelay = (uint8_t) delay;
        v.lfoPitchModDepth = (uint8_t) pmd; v.lfoAmpModDepth = (uint8_t) amd;
        v.lfoWave = (uint8_t) wave; v.lfoPitchModSens = (uint8_t) pitchSens;
    }

